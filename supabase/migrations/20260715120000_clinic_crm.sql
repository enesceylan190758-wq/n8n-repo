-- ── Segment kataloğu (Stella ekranından doğrulanmış liste) ───
-- show_in_dynamic=true olanlar not kaydından sonra gun_offset gün sonra
-- Dinamik Arama listesine düşer (next_call_date hesaplanır).
create table if not exists public.crm_segments (
  code text primary key,
  label text not null,
  show_in_dynamic boolean not null default true,
  gun_offset int not null default 1,
  sira int not null default 100,
  aktif boolean not null default true
);

