-- ── Kişiler: lead + danışan tek tablo ────────────────────────
-- stage: 'lead' (henüz atanmamış/ham) → 'danisan' (temsilciye atanmış).
-- next_call_date: Dinamik Arama kuyruğu = next_call_date <= bugün.
create table if not exists public.crm_contacts (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null default '51738ea8-c12e-40ce-a0e2-42869496d76b',
  file_no bigint generated by default as identity (start with 11150),
  stage text not null default 'lead' check (stage in ('lead', 'danisan')),
  status text not null default 'aktif' check (status in ('aktif', 'arsiv')),
  ad text not null,
  telefon text,
  ulke text default '',
  kaynak text default '',
  kampanya text default '',
  assigned_to uuid references public.crm_users(id),
  segment_code text references public.crm_segments(code),
  next_call_date date,
  created_by uuid references public.crm_users(id),
  updated_by uuid references public.crm_users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists crm_contacts_dynamic_idx
  on public.crm_contacts (next_call_date, status) where next_call_date is not null;
create index if not exists crm_contacts_assigned_idx on public.crm_contacts (assigned_to);
create index if not exists crm_contacts_stage_idx on public.crm_contacts (stage);
create index if not exists crm_contacts_telefon_idx on public.crm_contacts (telefon);

-- ── Not geçmişi ──────────────────────────────────────────────
create table if not exists public.crm_contact_notes (
  id uuid primary key default gen_random_uuid(),
  contact_id uuid not null references public.crm_contacts(id) on delete cascade,
  body text not null,
  segment_code text references public.crm_segments(code),
  note_date date,
  created_by uuid references public.crm_users(id),
  created_at timestamptz not null default now()
);

create index if not exists crm_contact_notes_contact_idx
  on public.crm_contact_notes (contact_id, created_at desc);

-- ── Randevular ───────────────────────────────────────────────
create table if not exists public.crm_appointments (
  id uuid primary key default gen_random_uuid(),
  contact_id uuid not null references public.crm_contacts(id) on delete cascade,
  start_at timestamptz not null,
  end_at timestamptz,
  hizmet text default '',
  personel text default '',
  oda text default '',
  tip text default '',
  durum text not null default 'beklemede'
    check (durum in ('beklemede', 'geldi', 'tamamlandi', 'iptal', 'gelmedi')),
  not_text text default '',
  created_by uuid references public.crm_users(id),
  updated_by uuid references public.crm_users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists crm_appointments_start_idx on public.crm_appointments (start_at);
create index if not exists crm_appointments_contact_idx on public.crm_appointments (contact_id);

-- ── updated_at trigger ───────────────────────────────────────
create or replace function public.crm_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_crm_contacts_touch on public.crm_contacts;
create trigger trg_crm_contacts_touch
before update on public.crm_contacts
for each row execute function public.crm_touch_updated_at();

drop trigger if exists trg_crm_appointments_touch on public.crm_appointments;
create trigger trg_crm_appointments_touch
before update on public.crm_appointments
for each row execute function public.crm_touch_updated_at();

