revoke all on table public.crm_contact_notes from anon, authenticated;
revoke all on table public.crm_appointments from anon, authenticated;

grant select, insert, update, delete on table public.crm_users to service_role;
grant select, insert, update, delete on table public.crm_segments to service_role;
grant select, insert, update, delete on table public.crm_contacts to service_role;
grant select, insert, update, delete on table public.crm_contact_notes to service_role;
grant select, insert, update, delete on table public.crm_appointments to service_role;
